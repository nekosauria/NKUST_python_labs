# =====================================================================
# 💡 參數逐行詳細解析：
# =====================================================================
# curl                                      # 終端機的網路傳輸工具
#   -i                                      # [隨附] 印出伺服器回傳的 HTTP 標頭 (Header)，如 200 OK, 403, 500
#   -v                                      # [詳細模式] 顯示整個連線過程的握手細節、傳輸狀態 (除錯必備)
#   -X POST                                 # 指定使用 POST 方法發送請求
#   http://<your_host>:<your_port>/upload            # 目標 API 網址 (10.0.0.12 是內網 IP，5566 是 Flask 監聽的 Port)
#   -F "image=@<your_img_path>" \
#                                           # [表單欄位 1] 模擬網頁上傳檔案 (multipart/form-data)
#                                           # Key 名稱為 "image"，"@" 後面接 Mac 當地實體圖片路徑
#   -F "model=<model_name>"                 # [表單欄位 2] 傳送額外文字參數，指定後端使用 "yolo" 或 "torch" 模型進行辨識
#
# ⚠️ 注意事項：
#   末尾的反斜線 `\` 代表「指令換行連接符」，能讓多行指令在終端機被視為同一筆執行。
#   複製時請確保 `\` 後面沒有多餘的空白，否則會執行失敗！
# =====================================================================


# 使用 curl 工具發送 HTTP 請求
curl -i -v -X POST https://nkust.nekosaur.com/upload \
  -F "image=@/Users/teddylai/Downloads/tmp/picture/cat0.jpg" \
  -F "model=torch"
