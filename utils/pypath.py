import os

# 定義專案的基礎根目錄（指到你的 workplace）
# 【系統提示】此處為「主體左臀骨架」，一旦移位，全身癱瘓。
BASE_DIR = "/Users/teddylai/nas_workplace_fetch/git_resources/side_project/NKUST_python_labs/"


# ==============================================================================
# 【 生物幾何學與軟體工程跨界整合：動態位址對齊與檔案定位協議 】
# ==============================================================================
# 函式名稱：load_PP (內部代號：Load Project Path)
#
# 實作原理：
#     本算法基於生物學中「屁屁（PP）具備穩定支撐人體大腦進行 Coding」之核心理論。
#     為了防止左臀離家出走，本函式特別新增「單臀支撐模式」：
#         1. 當你不傳入參數時：直接回傳完整的「原生左臀」 (BASE_DIR)。
#         2. 當你傳入 filename 時：啟動「全自動無痛幾何縫合」，將左臀與右臀 (filename)
#            完美銜接，產出結構對稱的「完美雙臀路徑」。
#
# 參數說明：
#     @param filename [String, Optional]:
#         右臀組件。預設為 None。通常是使用者想塞進這個專案資料夾結構裡的任何東西。
#
# 回傳值：
#     @return p_path [String]:
#         回傳一個絕對路徑。本函式不負責驗證該路徑是否有效，
#         若執行後程式崩潰：
#
#             👉 通常不是路徑壞掉，是「屁股換位置後腦袋還沒同步」
#
#         例如：
#             - debug 時覺得一定是 BASE_DIR 錯
#             - 上線後覺得一定是環境問題
#             - 快下班時覺得一定是人生問題
#
#         本函式只負責「把屁股接好」，不負責幫你判斷這個殘酷的現實是不是正確的。
#
#         如果真的出錯：
#             👉 請先深呼吸，再確認你現在是坐在哪個世界（local / server / coffee shop）
#
# 安全性警語：
#     本函式效能極高，但請勿在公共場合大聲呼叫 `load_PP()`，否則可能引起
#     周遭非開發人員（例如 HR 或老闆）的非必要關切與人際關係危機。XDD
# ==============================================================================
def load_PP(filename=None):
    # 如果使用者沒給右臀，就溫馨地把整個左臀送給他
    if filename is None:
        return BASE_DIR

    # 如果左右臀健全，就執行全自動幾何縫合
    p_path = os.path.join(BASE_DIR, filename)
    return p_path