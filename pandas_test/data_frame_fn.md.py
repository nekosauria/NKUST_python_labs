# DataFrame 統計函數（Pandas）
# ================================

# count()      : 非 NaN 值計數（統計有效資料筆數）
# mode()       : 眾數（出現次數最多的值）
# median()     : 中位數（排序後的中間值）
# quantile()   : 分位數（percentile）
#                q=0.25 -> 第一四分位數 (Q1)
#                q=0.50 -> 第二四分位數 (Median)
#                q=0.75 -> 第三四分位數 (Q3)

# mean()       : 平均數
# max()        : 最大值
# min()        : 最小值
# sum()        : 總和

# var()        : 變異數（資料離散程度）
# std()        : 標準差（變異數開根號）

# cov()        : 共變異數（兩個變數一起變動的關係）
# corr()       : 相關係數（-1 ~ 1，線性關係強度）

# cumsum()     : 累積總和（running total）
# cumprod()    : 累積乘積（running product）